CREATE TABLE USUARIOS(
ID_USER NUMBER GENERATED BY DEFAULT AS IDENTITY,
USERNAME VARCHAR2(20)NOT NULL,
PASS VARCHAR2(500) NOT NULL,
ROL VARCHAR2(15) NOT NULL,
ESTADO_USER VARCHAR2(15) NOT NULL,

CONSTRAINT ESTADO_USER_CHK CHECK (ESTADO_USER IN ('ELIMINADO','ACTIVO')),
CONSTRAINT ROL_USER_CHK CHECK (ROL IN ('ADMIN','USER'))
);

CREATE TABLE RESERVACIONES(
ID_RESERVACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
ID_HUESPED NUMBER NOT NULL,
ID_HABITACION NUMBER NOT NULL,
FECHA_ENTRADA DATE,
FECHA_SALIDA DATE,
ESTADO_RESERVACION VARCHAR2(15) NOT NULL,

CONSTRAINT ESTADO_RESERVACION_CHK CHECK (ESTADO_RESERVACION IN ('CONFIRMADA','EN CURSO','FINALIZADA','CANCELADA'))
);

CREATE TABLE HABITACIONES(
ID_HABITACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
NUMERO_HABITACION NUMBER (10)NOT NULL,
TIPO_HABITACION VARCHAR2(25) NOT NULL,
PRECIO NUMBER (10,2),
CAPACIDAD NUMBER (15) NOT NULL,
ESTADO_HABITACION VARCHAR2(15) NOT NULL,

CONSTRAINT TIPO_HABITACION_CHK CHECK (TIPO_HABITACION IN ('SENCILLA','SUITE','FAMILIAR','EJECUTIVA')),
CONSTRAINT ESTADO_HABITACION_CHK CHECK (ESTADO_HABITACION IN ('DISPONIBLE','OCUPADA','LIMPIEZA','MANTENIMIENTO'))
);


CREATE TABLE HUESPEDES(
ID_HUESPED NUMBER GENERATED BY DEFAULT AS IDENTITY,
NOMBRE VARCHAR2(50) NOT NULL,
APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
APELLIDO_MATERNO VARCHAR2 (50) NOT NULL,
EMAIL VARCHAR2(100) NOT NULL,
TELEFONO VARCHAR2(10) NOT NULL,
DOCUMENTO VARCHAR2 (50) NOT NULL,
NACIONALIDAD VARCHAR2(25) NOT NULL,
ESTADO_REGISTRO VARCHAR2(30)NOT NULL,

CONSTRAINT HUESPED_TELEFONO_CHK CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{10}$')), 

	  CONSTRAINT HUESPED_ESTADO_REGISTRO CHECK (ESTADO_REGISTRO IN ('ACTIVO','ELIMINADO'))

);